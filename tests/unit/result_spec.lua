-- Covers: TST-PLN-0006 TST-PLN-0007
local H = ...
local Store = require("planreview.store")
local result = require("planreview.result")
local export = require("planreview.export")

local function plan_info()
  return { path = "/tmp/plans/x.md", lines = { "# Title", "", "## A", "one", "two", "## B", "three" } }
end

H.describe("result.serialize", function()
  H.it("encodes an empty review with note null and comments []", function()
    local data = result.serialize(Store.new(), plan_info())
    H.assert.ok(result.is_approval(data))
    local json = vim.json.encode(data)
    H.assert.truthy(json:find('"note":null', 1, true), json)
    H.assert.truthy(json:find('"comments":[]', 1, true), json)
    H.assert.eq(data.version, 1)
    H.assert.truthy(data.id:match("^%d%d%d%d%d%d%d%dT%d%d%d%d%d%d$"), data.id)
    H.assert.eq(data.plan.line_count, 7)
    H.assert.eq(#data.plan.sha256, 64)
    H.assert.eq(data.plan.path, "/tmp/plans/x.md")
    H.assert.truthy(data.markdown:find("approved", 1, true))
  end)

  H.it("sorts comments, fills end_lineno, and nulls missing fields", function()
    local s = Store.new()
    s:add({ kind = "range", lineno = 4, end_lineno = 5, heading = "## A", text = "one\ntwo", body = "merge these" })
    s:add({ kind = "line", lineno = 2, body = "blank?" })
    s:add({ kind = "section", lineno = 6, end_lineno = 7, heading = "## B", body = "drop B" })
    s:set_note("overall fine")
    local data = result.serialize(s, plan_info())
    H.assert.eq(result.is_approval(data), false)
    H.assert.eq(#data.comments, 3)
    H.assert.eq(data.comments[1].lineno, 2)
    H.assert.eq(data.comments[1].end_lineno, 2)
    H.assert.eq(data.comments[1].heading, vim.NIL)
    H.assert.eq(data.comments[1].text, vim.NIL)
    H.assert.eq(data.comments[2].kind, "range")
    H.assert.eq(data.comments[3].text, vim.NIL, "section comments carry no text")
    H.assert.eq(data.note, "overall fine")
    local json = vim.json.encode(data)
    H.assert.truthy(json:find('"heading":null', 1, true), json)
    H.assert.eq(data.markdown, export.to_markdown(data))
  end)

  H.it("the store never holds vim.NIL", function()
    local s = Store.new()
    s:add({ lineno = 1, body = "x" })
    result.serialize(s, plan_info())
    H.assert.is_nil(s:get(1).heading)
    H.assert.is_nil(s:get(1).text)
  end)
end)

H.describe("export.to_markdown", function()
  H.it("lists the note first, then anchored comments with quotes", function()
    local s = Store.new()
    s:set_note("overall")
    s:add({ kind = "range", lineno = 4, end_lineno = 5, heading = "## A", text = "one\ntwo", body = "merge" })
    s:add({ kind = "section", lineno = 6, end_lineno = 7, heading = "## B", body = "drop" })
    s:add({ kind = "line", lineno = 1, heading = "# Title", text = "# Title", body = "rename" })
    local md = export.to_markdown(result.serialize(s, plan_info()))
    local i_note = md:find("## Whole plan\n\noverall", 1, true)
    local i_l1 = md:find("## L1 (# Title)\n\n> # Title\n\nrename", 1, true)
    local i_l4 = md:find("## L4-5 (## A)\n\n> one\n> two\n\nmerge", 1, true)
    local i_l6 = md:find("## L6-7, section ## B\n\ndrop", 1, true)
    H.assert.truthy(md:find("^# Plan review: x.md\n"), md)
    H.assert.truthy(md:find("anchored to the plan as it was when reviewed", 1, true), "preamble present")
    H.assert.ok(md:find("anchored", 1, true) < i_note, "preamble precedes the comments")
    H.assert.truthy(i_note and i_l1 and i_l4 and i_l6, md)
    H.assert.ok(i_note < i_l1 and i_l1 < i_l4 and i_l4 < i_l6, "order")
    H.assert.is_nil(md:match("\n$"), "no trailing newline")
  end)
end)

H.describe("result.save", function()
  H.it("writes <dir>/<id>.json", function()
    local dir = vim.fn.tempname()
    local data = result.serialize(Store.new(), plan_info())
    local path = result.save(data, dir)
    H.assert.eq(path, dir .. "/" .. data.id .. ".json")
    local f = assert(io.open(path))
    local decoded = vim.json.decode(f:read("*a"))
    f:close()
    H.assert.eq(decoded.plan.line_count, 7)
    H.assert.eq(decoded.note, vim.NIL)
    vim.fn.delete(dir, "rf")
  end)
end)
